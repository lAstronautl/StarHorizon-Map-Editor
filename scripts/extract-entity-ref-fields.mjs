#!/usr/bin/env node
/**
 * Generates src/grid/entityRefFields.generated.ts: which component YAML fields hold entity uids.
 *
 * Scans the game's C# components for [DataField] members typed EntityUid / NetEntity (also inside
 * List / HashSet / Dictionary) so the editor can remap or drop references when entities move to
 * another map, grid or prefab.
 *
 *   node scripts/extract-entity-ref-fields.mjs <path-to-game-repo>
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(process.argv[2] ?? '../StarHorizon');
const scanDirs = ['Content.Shared', 'Content.Server', 'Content.Client', 'RobustToolbox/Robust.Shared'];

function* walk(dir) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    const st = statSync(full);
    if (st.isDirectory()) { if (name !== 'obj' && name !== 'bin') yield* walk(full); }
    else if (name.endsWith('.cs')) yield full;
  }
}

const CLASS = /\bclass\s+(\w+)Component\b/;
const MEMBER = /^\s*public\s+(?:virtual\s+|readonly\s+|new\s+)*([\w<>?,.\s()]+?)\s+(\w+)\s*(?:=|;|\{)/;
const UID = '(?:EntityUid|NetEntity)';

/** @returns {'uid' | 'list' | 'dictKey' | 'dictValue' | null} */
function kindOf(type) {
  const t = type.replace(/\s+/g, ' ').trim();
  if (new RegExp(`^${UID}\\??$`).test(t)) return 'uid';
  if (new RegExp(`^(?:List|HashSet|IReadOnlyList|ISet|IReadOnlySet)<${UID}\\??>\\??$`).test(t) || new RegExp(`^${UID}\\[\\]\\??$`).test(t)) return 'list';
  if (new RegExp(`^Dictionary<${UID}\\s*,`).test(t)) return 'dictKey';
  if (new RegExp(`^Dictionary<[^,]+,\\s*${UID}\\??>\\??$`).test(t)) return 'dictValue';
  return null;
}

const found = new Map();
for (const dir of scanDirs) {
  const base = join(root, dir);
  try { statSync(base); } catch { continue; }
  for (const file of walk(base)) {
    const lines = readFileSync(file, 'utf8').split('\n');
    let cls = null;
    lines.forEach((line, i) => {
      const c = CLASS.exec(line);
      if (c) cls = c[1];
      if (!cls) return;
      const m = MEMBER.exec(line);
      if (!m) return;
      const kind = kindOf(m[1]);
      if (!kind) return;
      const context = lines.slice(Math.max(0, i - 4), i + 1).join('\n');
      const attr = /\[DataField(?:\(\s*(?:"([^"]+)"|[^)"]*?"([^"]+)")?[^)]*\))?/.exec(context);
      if (!attr) return;
      const member = m[2];
      const name = attr[1] ?? attr[2] ?? member[0].toLowerCase() + member.slice(1);
      if (!found.has(cls)) found.set(cls, new Map());
      found.get(cls).set(name, kind);
    });
  }
}

const out = [...found.entries()].sort(([a], [b]) => a.localeCompare(b))
  .map(([cls, fields]) => `  ${cls}: { ${[...fields.entries()].map(([f, k]) => `${f}: '${k}'`).join(', ')} },`)
  .join('\n');

const header = `// GENERATED by scripts/extract-entity-ref-fields.mjs from the game's C# components. Do not edit.
// Maps a component name to the YAML fields that hold entity uids and how they hold them:
//   uid        a single entity
//   list       a sequence of entities
//   dictKey    a mapping keyed by entity
//   dictValue  a mapping whose values are entities
export type EntityRefKind = 'uid' | 'list' | 'dictKey' | 'dictValue';

export const ENTITY_REF_FIELDS: Record<string, Record<string, EntityRefKind>> = {
${out}
};
`;
const target = join(dirname(fileURLToPath(import.meta.url)), '../src/grid/entityRefFields.generated.ts');
writeFileSync(target, header);
console.log(`wrote ${found.size} components to ${target}`);
